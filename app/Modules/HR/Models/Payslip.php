<?php

namespace App\Modules\HR\Models;

use App\Modules\Settings\Models\User;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Payroll ledger record — one row per employee per calendar month.
 *
 * Lifecycle:  draft → approved → paid
 *
 * The payroll engine (PayrollCalculatorService) populates all monetary
 * fields. HR admins then approve and mark as paid via the PayslipController.
 *
 * @property int    $id
 * @property int    $user_id
 * @property int    $month                    1–12
 * @property int    $year
 * @property float  $base_salary
 * @property int    $points_earned
 * @property float  $points_bonus_amount
 * @property int    $lateness_minutes
 * @property float  $lateness_deduction_amount
 * @property float  $net_salary
 * @property string $status                   draft|approved|paid
 * @property-read User $user
 */
class Payslip extends Model
{
    use SoftDeletes;

    protected $fillable = [
        'user_id',
        'month',
        'year',
        'base_salary',
        'points_earned',
        'points_bonus_amount',
        'lateness_minutes',
        'lateness_deduction_amount',
        'net_salary',
        'status',
    ];

    protected function casts(): array
    {
        return [
            'month'                     => 'integer',
            'year'                      => 'integer',
            'base_salary'               => 'decimal:2',
            'points_earned'             => 'integer',
            'points_bonus_amount'       => 'decimal:2',
            'lateness_minutes'          => 'integer',
            'lateness_deduction_amount' => 'decimal:2',
            'net_salary'                => 'decimal:2',
        ];
    }

    // -------------------------------------------------------------------------
    // Relationships
    // -------------------------------------------------------------------------

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    // -------------------------------------------------------------------------
    // Scopes
    // -------------------------------------------------------------------------

    /** Filter by lifecycle status. */
    public function scopeOfStatus($query, string $status)
    {
        return $query->where('status', $status);
    }

    /** Filter to a specific calendar month/year. */
    public function scopeForPeriod($query, int $month, int $year)
    {
        return $query->where('month', $month)->where('year', $year);
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    /** Whether this payslip can still be regenerated by the payroll engine. */
    public function isDraft(): bool
    {
        return $this->status === 'draft';
    }
}
